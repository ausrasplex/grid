  phone: Smartphone,
  "user-plus": UserPlus,
  "chevron-down": ChevronDown,
  "chevron-right": ChevronRight,
  dollar: CircleDollarSign,
  scan: ScanLine,
  search: Search,
  wrench: Wrench,
  building: Building2,
  clipboard: ClipboardList,
  file: FileText,
